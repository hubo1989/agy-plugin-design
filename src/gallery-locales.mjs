export function createGalleryStrings(skills, recipes, examples) {
  const str = {};
  for (const loc of SUPPORTED_LOCALES) {
    const dict = { ...(UI_STRINGS[loc] || UI_STRINGS.en) };
    const skMap = SKILL_TRANSLATIONS[loc] || SKILL_TRANSLATIONS.en;
    const rcMap = RECIPE_TRANSLATIONS[loc] || {};
    const exMap = EXAMPLE_TRANSLATIONS[loc] || {};

    for (const skill of skills) {
      const entry = skMap[skill.id];
      dict[`skill.${skill.id}.name`] = entry ? entry[0] : (skill.nameEn || skill.name);
      dict[`skill.${skill.id}.about`] = entry ? entry[1] : skill.about;
      dict[`skill.${skill.id}.prompt`] = (entry && entry[2]) ? entry[2] : skill.prompt;
    }

    for (const recipe of recipes) {
      const entry = rcMap[recipe.id];
      dict[`recipe.${recipe.id}.title`] = entry ? entry[0] : recipe.title;
      dict[`recipe.${recipe.id}.desc`] = entry ? entry[1] : recipe.desc;
    }

    for (const example of examples) {
      const entry = exMap[example.id];
      dict[`example.${example.id}.title`] = entry ? entry[0] : example.title;
      dict[`example.${example.id}.desc`] = entry ? entry[1] : example.desc;
      dict[`example.${example.id}.points`] = entry ? entry[2] : example.points;
    }

    str[loc] = dict;
  }
  return str;
}
